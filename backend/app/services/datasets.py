FILE_RE = re.compile(r"^(train|test)_(source1|source2|source3|ground_truth)\.tsv$")


def _count_rows(path: Path) -> int:
    """Data rows (excluding header) by streaming newlines — O(1) memory for multi-GB files."""
    n = 0
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 22), b""):
            n += block.count(b"\n")
    with open(path, "rb") as fh:  # last line without trailing newline
        fh.seek(0, 2)
        if fh.tell():
            fh.seek(-1, 2)
            n += fh.read(1) != b"\n"
    return max(0, n - 1)


def file_info(root: Path, splits: list[str]) -> dict:
    """Per-file name / bytes / rows / header, cached by (path, size, mtime)."""
    import json

    cache_path = settings.path("processed_dir") / "file_stats_cache.json"
    try:
        cache = json.loads(cache_path.read_text())
    except Exception:
        cache = {}
    out = {}
    for sp in splits:
        rows = []
        for name in (f"{sp}_source1.tsv", f"{sp}_source2.tsv", f"{sp}_source3.tsv", f"{sp}_ground_truth.tsv"):
            p = Path(root) / sp / name
            if not p.exists():
                continue
            st = p.stat()
            key = f"{p.resolve()}|{st.st_size}|{int(st.st_mtime)}"
            if key not in cache:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    header = fh.readline().rstrip("\r\n").split("\t")
                cache[key] = {"rows": _count_rows(p), "columns": header}
            rows.append({"file": name, "bytes": st.st_size, **cache[key]})
        out[sp] = rows
    try:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(json.dumps(cache))
    except Exception:
        pass
    return out


def dataset_kind_of(root: Path, kind_hint: str) -> str:
    from src.data.data_loader import SYNTHETIC_MARKER

    if (Path(root) / SYNTHETIC_MARKER).exists():
        return "synthetic"
    if Path(root).resolve() == settings.path("dataset_dir").resolve():
        return "competition"
    return "custom" if kind_hint != "synthetic" else "synthetic"


def _splits(root: Path) -> list[str]:
    return [s for s in ("train", "test") if (root / s / f"{s}_source1.tsv").exists()]


def discover() -> None:
    """Register the competition dataset (paths.dataset_dir) and synthetic demo data if present."""
    candidates = [("competition", "Competition dataset", "competition", settings.path("dataset_dir"),
                   "Official challenge files (train with labels, test without)."),
                  ("synthetic-demo", "Synthetic demo data", "synthetic", PROJECT_ROOT / "data" / "synthetic",
                   "Generated by src/data/synthetic.py for development. Not competition data.")]
    with SessionLocal() as db:
        for did, name, kind, root, desc in candidates:
            sp = _splits(Path(root))
            row = db.get(Dataset, did)
            if sp and row is None:
                db.add(Dataset(id=did, name=name, kind=kind, root=str(root), splits=sp, description=desc))
            elif row is not None:
                row.splits = sp
        db.commit()


def list_datasets() -> list[dict]:
    discover()
    with SessionLocal() as db:
        rows = db.query(Dataset).order_by(Dataset.created).all()
        return [_dto(r) for r in rows if r.splits]


def get_dataset(did: str) -> Dataset | None:
    with SessionLocal() as db:
        return db.get(Dataset, did)


def _dto(r: Dataset) -> dict:
    counts = {}
    if r.profile:
        for split, p in r.profile.items():
            counts[split] = {k: v["records"] for k, v in p["profile"]["sources"].items()}
    return {"id": r.id, "name": r.name, "kind": r.kind, "data_kind": dataset_kind_of(Path(r.root), r.kind), "splits": r.splits,
            "created": r.created.isoformat() if r.created else None, "description": r.description,
            "profiled": bool(r.profile), "record_counts": counts, "has_labels": "train" in (r.splits or []),
            "files": file_info(Path(r.root), r.splits or [])}


def profile(did: str, refresh: bool = False) -> dict:
    with SessionLocal() as db:
        r = db.get(Dataset, did)
        if r is None:
            raise KeyError(did)
        if r.profile and not refresh:
            return r.profile
        total = sum(f["rows"] for fs in file_info(Path(r.root), r.splits or []).values() for f in fs)
        if total > 1_500_000:
            # multi-million-row datasets are profiled by the CLI (streamed, cached), never inside a web request
            import json

            cli = settings.path("experiments_dir") / "data_profile.json"
            if cli.exists():
                r.profile = json.loads(cli.read_text())
                db.commit()
                return r.profile
            raise ValueError(f"{total:,} rows: run `python -m src.cli profile` once to profile this dataset")
        out = {}
        for split in r.splits:
            ds = load_split(r.root, split)
            out[split] = {"validation": validate_dataset(ds).as_dict(), "profile": profile_dataset(ds)}
        r.profile = out
        db.commit()
        return out


def _check_tsv(name: str, content: bytes) -> list[str]:
    issues = []
    try:
        text = content.decode("utf-8-sig")
    except UnicodeDecodeError:
        return [f"{name}: not valid UTF-8"]
    first = text.split("\n", 1)[0].rstrip("\r")
    cols = [c.strip() for c in first.split("\t")]
    if name.endswith("ground_truth.tsv"):
        if cols != ["source1_entity_id", "matched_entity_ids"]:
            issues.append(f"{name}: header must be source1_entity_id<TAB>matched_entity_ids")
    elif any(c not in cols for c in REQUIRED_COLUMNS):
        issues.append(f"{name}: missing columns {[c for c in REQUIRED_COLUMNS if c not in cols]} (is it tab-separated?)")
    rows = list(csv.reader(io.StringIO(text), delimiter="\t", quoting=csv.QUOTE_NONE))
    bad = sum(1 for row in rows[1:] if row and len(row) != len(cols))
    if bad:
        issues.append(f"{name}: {bad} malformed rows (wrong number of tab-separated fields)")
    return issues


def save_upload(name: str, files: dict[str, bytes]) -> dict:
    """files: {original_filename: bytes}. Filenames must follow the competition naming convention."""
    issues: list[str] = []
    safe: dict[str, bytes] = {}
    limit = settings.max_upload_mb * 2**20
    for fname, content in files.items():
        base = Path(fname).name  # strips any directory components (path traversal)
        if not FILE_RE.match(base):
            issues.append(f"{base}: expected <split>_source1|2|3.tsv or <split>_ground_truth.tsv")
            continue
        if len(content) > limit:
            issues.append(f"{base}: exceeds {settings.max_upload_mb} MB")
            continue
        issues += _check_tsv(base, content)
        safe[base] = content
    splits = {FILE_RE.match(b).group(1) for b in safe}
    for sp in splits:
        need = {f"{sp}_source{k}.tsv" for k in (1, 2, 3)}
        if not need <= set(safe):
            issues.append(f"split '{sp}' needs {sorted(need - set(safe))}")
    if issues:
        return {"ok": False, "issues": issues}
    did = f"upload-{uuid.uuid4().hex[:10]}"
    root = settings.uploads_dir / did
    for base, content in safe.items():
        sp = FILE_RE.match(base).group(1)
        d = root / sp
        d.mkdir(parents=True, exist_ok=True)
        (d / base).write_bytes(content)
    clean_name = re.sub(r"[^\w\s\-.]", "", name)[:120] or did
    with SessionLocal() as db:
        db.add(Dataset(id=did, name=clean_name, kind="upload", root=str(root), splits=sorted(splits),
                       description="Uploaded via the web application"))
        db.commit()
    return {"ok": True, "id": did, "splits": sorted(splits)}
